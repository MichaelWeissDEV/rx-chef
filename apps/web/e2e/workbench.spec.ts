import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
const token = 'browser-test-token-0123456789';
test('public assets, protected API, memory session, binary import/export and reload', async ({ page, request }) => {
  expect((await request.get('/')).status()).toBe(200);
  expect((await request.get('/api/v1/operations')).status()).toBe(401);
  await page.addInitScript(() => localStorage.setItem('rxchef_token', 'legacy-secret'));
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByLabel('Server Bearer Token').fill(token);
  await page.getByRole('button', { name: 'Connect (this session)' }).click();
  await expect(page.getByText('Operations (478)')).toBeVisible();
  expect(await page.evaluate(() => localStorage.getItem('rxchef_token'))).toBeNull();
  expect(await page.evaluate(() => sessionStorage.getItem('rxchef_token'))).toBeNull();
  await page.getByTitle('Clear recipe').click();
  const bytes = Buffer.from(Array.from({ length: 256 }, (_, i) => i));
  await page.getByLabel('Input file').setInputFiles({ name: 'all-bytes.bin', mimeType: 'application/octet-stream', buffer: bytes });
  await expect(page.getByLabel('Input data')).toHaveText(bytes.toString('base64'));
  await page.getByRole('button', { name: 'Bake', exact: true }).click();
  await expect(page.getByText('Output (256 bytes)')).toBeVisible();
  await expect(page.getByRole('note')).toContainText('lossy');
  const downloaded = page.waitForEvent('download');
  await page.getByTitle('Download Raw Bytes').click();
  expect(await readFile((await (await downloaded).path())!)).toEqual(bytes);
  await page.getByPlaceholder('Search operations...').fill('To Hex');
  await page.locator('.op-item').filter({ has: page.getByText('To Hex', { exact: true }) }).getByTitle('Add to Recipe').click();
  await page.getByRole('button', { name: 'Bake', exact: true }).click();
  await expect(page.getByText('Output (767 bytes)')).toBeVisible();
  await page.getByTitle('Switch to light mode').click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  await page.reload();
  await expect(page.getByLabel('Server Bearer Token')).toHaveValue('');
  await expect(page.getByText('Operations (0)')).toBeVisible();
  expect(errors).toEqual([]);
});
