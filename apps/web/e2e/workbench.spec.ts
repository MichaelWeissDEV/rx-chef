test('recipe history, metadata defaults, save/load, trace and narrow window', async ({ page }) => {
  await page.goto('/');
  await page.getByLabel('Server Bearer Token').fill(token);
  await page.getByRole('button', { name: 'Connect (this session)' }).click();
  await expect(page.getByText('Operations (478)')).toBeVisible();
  await page.getByTitle('Clear recipe').click();
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(page.getByText('Recipe (1 steps)')).toBeVisible();
  await page.getByRole('button', { name: 'Redo', exact: true }).click();
  await expect(page.getByText('Recipe (0 steps)')).toBeVisible();
  await page.getByRole('button', { name: 'Commands', exact: false }).click();
  await page.getByLabel('Find operation').fill('To Hex');
  await page.getByRole('dialog').getByRole('button', { name: 'Add To Hex', exact: true }).click();
  await expect(page.getByLabel('Delimiter')).toHaveValue('Space');
  await page.getByRole('button', { name: 'Bake', exact: true }).click();
  await expect(page.getByLabel('Trace inspector')).toBeVisible();
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Save recipe' }).click();
  const saved = await readFile((await (await downloaded).path())!);
  await page.getByTitle('Clear recipe').click();
  await page.getByLabel('Recipe file').setInputFiles({ name: 'recipe.json', mimeType: 'application/json', buffer: saved });
  await expect(page.getByText('Recipe (1 steps)')).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});
